def get_vectorstore():
    from langchain_chroma import Chroma
    from langchain_huggingface import HuggingFaceEmbeddings
    embeddings = HuggingFaceEmbeddings(model_name=EMBED_MODEL,
                                       encode_kwargs={"normalize_embeddings": True})
    return Chroma(collection_name=COLLECTION, embedding_function=embeddings,
                  persist_directory=DB_DIR, collection_metadata={"hnsw:space": "cosine"})


def ingest(vs) -> None:
    t0 = time.perf_counter()
    docs = load_kb()
    chunks = chunk_documents(docs)
    new_ids = {c.metadata["chunk_id"] for c in chunks}
    old_ids = set(vs.get(include=[])["ids"])
    stale = old_ids - new_ids          # outdated guideline text is removed, not kept
    fresh = [c for c in chunks if c.metadata["chunk_id"] not in old_ids]
    if stale:
        vs.delete(ids=list(stale))
    for i in range(0, len(fresh), 500):   # batches: large books have thousands of chunks
        batch = fresh[i:i + 500]
        vs.add_documents(batch, ids=[c.metadata["chunk_id"] for c in batch])
        if len(fresh) > 500:
            print(f"[ingest] embedded {min(i + 500, len(fresh))}/{len(fresh)} chunks")
    print(f"[ingest] {len(docs)} docs -> {len(chunks)} chunks | +{len(fresh)} new, "
          f"-{len(stale)} stale | {time.perf_counter() - t0:.2f}s")


# --------------------------------------------------------------------------- #
# 5. Retriever with relevance gate + diversity across conditions
# --------------------------------------------------------------------------- #
def retrieve(vs, query: str):
    hits = vs.similarity_search_with_relevance_scores(query, k=FETCH_K)
    hits = [(d, s) for d, s in hits if s >= MIN_RELEVANCE]
    # Diversity: at most 2 chunks per condition so the differential stays broad
    # (recall over precision: missing a dangerous condition is worse than an extra one).
    per_condition, selected = {}, []
    for d, s in hits:
        cond = d.metadata.get("condition") or f"{d.metadata['source']}#p{d.metadata.get('page', '')}"
        if per_condition.get(cond, 0) < 2:
            selected.append((d, s))
            per_condition[cond] = per_condition.get(cond, 0) + 1
        if len(selected) == TOP_K:
            break
    return selected


# Query expansion ("advanced RAG"): the LLM suggests candidate conditions ONLY to improve the
# search. A list of separate symptoms (tired, cold, dry skin...) otherwise matches the separate
# symptom pages instead of the disease page (e.g. Hypothyroidism). The answer itself is still
# written only from the retrieved MedlinePlus passages.
EXPAND_PROMPT = ChatPromptTemplate.from_messages([
    ("system", "You help a search engine over MedlinePlus health topics. Given a symptom description, "
               "list up to 5 conditions (MedlinePlus topic names) that could explain the symptoms TOGETHER, "
               "most likely first. Reply with the names only, separated by commas. "
               "If the text is not about health or symptoms, reply NONE."),
    ("human", "{text}"),
])
EXPAND_MIN = 0.40        # a suggested condition must match a topic this well to be added
TOP_K_EXPANDED = 8


def expand_query(llm, text: str) -> list[str]:
    if llm is None:
        return []
    try:
        out = (EXPAND_PROMPT | llm | StrOutputParser()).invoke({"text": text})
    except Exception:
        return []
    if out.strip().upper().startswith("NONE"):
        return []
    names = [n.strip(" .-*•\t\"'") for n in re.split(r"[,\n;]", out)]
    return [n for n in names if 2 < len(n) < 60][:5]


def retrieve_expanded(vs, query: str, llm) -> tuple[list, list[str]]:
    """Normal retrieval (with the relevance gate) + one best passage per suggested condition."""
    base = retrieve(vs, query)
    if not base:                      # the gate still decides: nothing relevant -> refuse
        return [], []
    names = expand_query(llm, query)
    chosen, seen = [], set()
    key = lambda d: d.metadata.get("chunk_id") or d.page_content[:120]
    for name in names:
        for d, sc in vs.similarity_search_with_relevance_scores(name, k=3):
            if sc >= EXPAND_MIN and key(d) not in seen:
                chosen.append((d, sc)); seen.add(key(d))
                break
    for d, sc in base:
        if len(chosen) >= TOP_K_EXPANDED:
            break
        if key(d) not in seen:
            chosen.append((d, sc)); seen.add(key(d))
    return chosen, names


