# --------------------------------------------------------------------------- #
# Safety layer 1: input de-identification (PHI scrubbing, regex baseline)
# Production: use a clinical NER de-identification model (e.g. Microsoft Presidio).
# --------------------------------------------------------------------------- #
PHI_PATTERNS = [
    (re.compile(r"\b[\w.+-]+@[\w-]+\.[\w.]+\b"), "[EMAIL]"),
    (re.compile(r"\+?\d[\d\s().-]{7,}\d"), "[PHONE/ID]"),
    (re.compile(r"\b\d{1,2}[./-]\d{1,2}[./-]\d{2,4}\b"), "[DATE]"),
    (re.compile(r"\b(?:MRN|EGN|SSN|patient id)[:#\s]*\w+\b", re.I), "[ID]"),
    (re.compile(r"\b(?i:my name is|i am|i'm|patient)\s+[A-Z][a-z]+(?:\s+[A-Z][a-z]+)?"),
     "[NAME]"),
]


def scrub_phi(text: str) -> str:
    for pattern, token in PHI_PATTERNS:
        text = pattern.sub(token, text)
    return text


# --------------------------------------------------------------------------- #
# Safety layer 2: deterministic red-flag triage. Runs BEFORE and independently of
# the LLM, so emergency escalation never depends on a probabilistic model.
# Each rule fires if ALL of its pattern groups match (an AND of ORs).
# --------------------------------------------------------------------------- #
RED_FLAG_RULES = [
    ("Possible acute coronary syndrome",
     [r"chest (pain|pressure|tightness)",
      r"arm|jaw|sweat|short(ness)? of breath|breathless|nause|faint"]),
    ("Possible stroke (FAST)",
     [r"face (droop|drooping)|facial droop|slurred speech|one[- ]sided weakness|"
      r"can'?t (move|lift) (my|one|the) (arm|leg)|sudden (numbness|confusion|vision loss)"]),
    ("Possible meningitis",
     [r"fever|temperature|feverish", r"stif+\w*\s+ne\w*|neck\s+(is\s+)?stif+|non[- ]blanching rash|purple rash"]),
    ("Possible subarachnoid haemorrhage",
     [r"worst headache|thunderclap|sudden sever\w* headache"]),
    ("Respiratory emergency",
     [r"can'?t breathe|severe (shortness of breath|breathlessness)|blue lips|"
      r"coughing (up )?blood"]),
    ("Loss of consciousness / seizure",
     [r"unconscious|passed out|fainted|seizure|convulsion"]),
    ("Mental health crisis",
     [r"suicid|kill myself|end my life|self[- ]harm"]),
    ("Severe bleeding", [r"heavy bleeding|won'?t stop bleeding|vomiting blood"]),
]


def detect_red_flags(text: str) -> list[str]:
    t = text.lower()
    return [name for name, groups in RED_FLAG_RULES
            if all(re.search(g, t) for g in groups)]


# --------------------------------------------------------------------------- #
# 1. Ingestion -> 2. Medical-aware chunking
# --------------------------------------------------------------------------- #
FRONT_MATTER = re.compile(r"^---\n(.*?)\n---\n", re.S)


def load_kb() -> list[Document]:
    docs = []
    for path in sorted(KB_DIR.glob("*.md")):
        raw = path.read_text(encoding="utf-8")
        meta = {"source": path.name}
        m = FRONT_MATTER.match(raw)
        if m:  # YAML-style front matter -> provenance metadata
            for line in m.group(1).splitlines():
                key, _, val = line.partition(":")
                meta[key.strip()] = val.strip()
            raw = raw[m.end():]
        docs.append(Document(page_content=raw, metadata=meta))
    for path in sorted(KB_DIR.glob("*.txt")):
        docs.append(Document(page_content=path.read_text(encoding="utf-8", errors="ignore"),
                             metadata={"source": path.name, "last_reviewed": "unknown"}))
    # PDFs (guidelines, open-access books): one Document per page
    for path in sorted(KB_DIR.glob("*.pdf")):
        from langchain_community.document_loaders import PyPDFLoader
        pages = [d for d in PyPDFLoader(str(path)).load() if d.page_content.strip()]
        if not pages:
            print(f"[warn] {path.name}: no extractable text (scanned PDF? needs OCR)")
        for d in pages:
            d.metadata = {"source": path.name, "page": int(d.metadata.get("page", 0)) + 1,
                          "last_reviewed": "unknown"}
            docs.append(d)
    return docs


def chunk_documents(docs: list[Document]) -> list[Document]:
    """Section-aware chunking: split on clinical headers first (presentation, red flags,
    differential, workup), then size-limit. The condition name and section title are
    prepended to each chunk so a chunk is self-describing ('contextual chunk headers')."""
    header_splitter = MarkdownHeaderTextSplitter(
        headers_to_split_on=[("#", "condition"), ("##", "section")], strip_headers=True)
    size_splitter = RecursiveCharacterTextSplitter(
        chunk_size=CHUNK_SIZE, chunk_overlap=CHUNK_OVERLAP,
        separators=["\n\n", "\n", ". ", " ", ""])

    chunks, seen = [], set()
    for doc in docs:
        sections = (header_splitter.split_text(doc.page_content)
                    if doc.metadata["source"].endswith(".md") else [doc])
        for sec in sections:
            meta = {**doc.metadata, **sec.metadata}
            for piece in size_splitter.split_text(sec.page_content):
                if "condition" in meta:
                    header = f"{meta['condition']} - {meta.get('section', '')}".strip(" -")
                else:  # PDF/TXT: file name + page as context header
                    header = f"{Path(meta['source']).stem}" + (f" (p. {meta['page']})" if "page" in meta else "")
                text = f"{header}\n{piece}" if header else piece
                cid = hashlib.sha256(f"{meta['source']}::{meta.get('page', '')}::{text}".encode()).hexdigest()[:16]
                if cid in seen:   # identical text (e.g. repeated headers/footers): skip
                    continue
                seen.add(cid)
                chunks.append(Document(page_content=text, metadata={**meta, "chunk_id": cid}))
    return chunks


