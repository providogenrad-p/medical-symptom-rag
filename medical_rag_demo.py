def format_context(hits) -> str:
    return "\n\n".join(
        f"[{i}] (source: {d.metadata['source']}"
        f"{', page ' + str(d.metadata['page']) if 'page' in d.metadata else ''}, reviewed: "
        f"{d.metadata.get('last_reviewed', '?')}, relevance: {s:.2f})\n{d.page_content}"
        for i, (d, s) in enumerate(hits, 1))


def get_llm():
    if not os.getenv("GROQ_API_KEY"):
        return None
    from langchain_groq import ChatGroq
    model = os.getenv("GROQ_MODEL", "openai/gpt-oss-120b")
    extra = {}
    if model.startswith("openai/gpt-oss"):
        # reasoning model: keep reasoning short and out of the printed answer
        extra = {"reasoning_effort": "low"}   # reasoning is returned separately, not in the answer
    return ChatGroq(model=model, temperature=0, max_tokens=4000, **extra)


# Safety layer 3: output validation (citations must point to retrieved passages)
def validate_citations(answer: str, n_sources: int) -> list[str]:
    cited = {int(x) for x in re.findall(r"\[(\d+)\]", answer)}
    problems = []
    if not cited:
        problems.append("Answer contains no citations; treat as ungrounded.")
    invalid = sorted(c for c in cited if c < 1 or c > n_sources)
    if invalid:
        problems.append(f"Invalid citation numbers {invalid} (possible hallucination).")
    return problems


# --------------------------------------------------------------------------- #
# Public query function: symptoms in -> structured analysis out
# --------------------------------------------------------------------------- #
def analyze_symptoms(vs, llm, symptoms: str, age: int | None = None,
                     sex: str | None = None, duration: str | None = None,
                     detailed: bool = False) -> dict:
    patient = scrub_phi(symptoms)
    demo = ", ".join(x for x in [f"age {age}" if age else "", sex or "",
                                 f"duration {duration}" if duration else ""] if x)
    patient_desc = f"{patient} ({demo})" if demo else patient

    result = {"input": patient_desc, "red_flags": detect_red_flags(symptoms),
              "sources": [], "analysis": None, "warnings": [], "disclaimer": DISCLAIMER}

    t0 = time.perf_counter()
    hits, result["expanded"] = retrieve_expanded(vs, patient_desc, llm)
    result["retrieval_ms"] = round((time.perf_counter() - t0) * 1000)
    result["sources"] = [{"n": i, "source": d.metadata["source"],
                          "section": d.metadata.get("section"),
                          "condition": d.metadata.get("condition") or
                                       f"{d.metadata['source']} p.{d.metadata.get('page', '?')}",
                          "relevance": round(s, 2)}
                         for i, (d, s) in enumerate(hits, 1)]

    if not hits:  # relevance gate: refuse rather than hallucinate
        result["analysis"] = ("The knowledge base contains no sufficiently relevant "
                              "information for these symptoms. No analysis generated. "
                              "Please consult a healthcare professional.")
        return result
    if llm is None:
        result["warnings"].append("GROQ_API_KEY not set: retrieval-only mode.")
        return result

    chain = PROMPT | llm | StrOutputParser()
    t1 = time.perf_counter()
    answer = chain.invoke({
        "context": format_context(hits), "patient": patient_desc,
        "red_flags": "; ".join(result["red_flags"]) or "none detected by rules",
        "format_rules": FORMAT_DETAILED if detailed else FORMAT_SHORT})
    result["generation_ms"] = round((time.perf_counter() - t1) * 1000)
    # some models (e.g. gpt-oss) write citations as 【1】 - normalise to [1]
    answer = re.sub(r"[【〔［]\s*(\d+)\s*[】〕］]", r"[\1]", answer)
    result["analysis"] = answer
    result["warnings"] += validate_citations(answer, len(hits))
    return result


def _render_markdown(text: str) -> None:
    try:   # optional: pip install rich  -> nicely formatted answer in the terminal
        from rich.console import Console
        from rich.markdown import Markdown
        Console().print(Markdown(text))
    except ImportError:
        print(text)


def print_result(r: dict) -> None:
    line = "-" * 78
    print(f"\n{line}\nYou: {r['input']}")
    if r["red_flags"]:
        print(f"\n!!! RED FLAGS: {', '.join(r['red_flags'])}")
        print("!!! SEEK EMERGENCY CARE NOW - call 112 (EU) / 911 (US).")
    if r["analysis"]:
        ms = f" ({r['generation_ms']} ms)" if "generation_ms" in r else ""
        print(f"\nAssistant{ms}:")
        _render_markdown(r["analysis"])
    also = f" | also searched: {', '.join(r['expanded'])}" if r.get("expanded") else ""
    print(f"\nSources (retrieved in {r['retrieval_ms']} ms{also}):")
    for s in r["sources"]:
        sec = f" - {s['section']}" if s["section"] else ""
        print(f"  [{s['n']}] {s['condition']}{sec}  (relevance {s['relevance']})")
    for w in r["warnings"]:
        print(f"\n[warning] {w}")
    if any(s["source"].startswith("mplus_") for s in r["sources"]):
        print("\nSource: MedlinePlus.gov, U.S. National Library of Medicine (public domain).")
    print(f"{r['disclaimer']}\n{line}")


def main():
    ap = argparse.ArgumentParser(description="Medical Symptom Analysis RAG (educational)")
    ap.add_argument("--ingest", action="store_true", help="(re)build the index")
    ap.add_argument("--symptoms", type=str, help="free-text symptoms")
    ap.add_argument("--age", type=int)
    ap.add_argument("--sex", type=str)
    ap.add_argument("--duration", type=str)
    ap.add_argument("--detailed", action="store_true", help="full clinical table instead of a short answer")
    args = ap.parse_args()

    print(f"Medical RAG demo {VERSION} | model: {os.getenv('GROQ_MODEL', 'openai/gpt-oss-120b')}")
    print("*** Educational prototype - not a medical device - not medical advice ***")
    ensure_seed_kb()
    vs = get_vectorstore()
    if args.ingest or not vs.get(limit=1)["ids"]:
        ingest(vs)
    if args.ingest and not args.symptoms:
        return
    llm = get_llm()

    if args.symptoms:
        print_result(analyze_symptoms(vs, llm, args.symptoms, args.age, args.sex,
                                      args.duration, args.detailed))
        return
    print("Describe symptoms (or 'exit').")
    while (q := input("\nsymptoms> ").strip()).lower() not in {"exit", "quit"}:
        if q:
            print_result(analyze_symptoms(vs, llm, q, detailed=args.detailed))


if __name__ == "__main__":
    main()
